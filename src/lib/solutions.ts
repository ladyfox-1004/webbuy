// 업종별 솔루션 페이지의 데이터.
//
// 🚨 이 페이지들의 무게중심은 "사례 소개"가 아니라 **"이 업종에 달 수 있는 기능 카탈로그"** 다.
//    사장님 지시: "내가 어떤 것까지 다룰 수 있고 개발할 수 있는지, 여기서 어떻게 더 개발할 수
//    있는지를 기능별로 자세히 풀어 설명하는 게 더 중요하다. 사이트는 그냥 사진 정도로만."
//    그래서 featureGroups 가 가장 길고, cases 는 스크린샷 썸네일 + 이름뿐이다.
//
// 🚨 기능 목록과 사례를 1:1로 묶지 마라. featureGroups 는 "달 수 있는 기능"이고,
//    cases 는 "만든 사이트"다. 둘을 이어 붙이면 하지 않은 것을 했다고 쓰는 셈이 된다.
//
// 🚨 금액은 어디에도 쓰지 않는다(사이트 전체 방침).
//
// 사례 이름은 src/lib/portfolio.ts 의 portfolioSites 에서 " · " 앞부분을 그대로 적는다.
// 이름이 안 맞으면 그 사례는 조용히 빠지므로, 이름을 바꿀 때는 양쪽을 같이 본다.

export type FeatureGroup = {
  /** 방문자가 훑을 때 눈에 걸리는 제목 */
  title: string;
  /** 칩으로 촘촘히 뿌린다 */
  items: string[];
};

/**
 * 바로 문의할 수 있는 상품 단위. 지금은 /solutions/automation 에만 있다.
 * 🚨 금액·기간을 넣지 않는다. 해 본 적 없는 연동을 "된다"고 적지 않는다(제약은 note 에).
 */
export type Product = {
  name: string;
  /** 한 문장 */
  summary: string;
  /** 대상 업종 칩 */
  audience: string[];
  /** 하는 일 3~5개 */
  does: string[];
  /** 쓰는 API·서비스 칩 */
  integrations: string[];
  /** 주의 한 줄. 없으면 렌더하지 않는다 */
  note?: string;
};

/** 실제로 존재하는 라우트 경로만 적는다. 라우트를 추가/삭제하면 여기도 같이 고친다. */
export type SolutionPath =
  | "/solutions/hospital"
  | "/solutions/law"
  | "/solutions/realestate"
  | "/solutions/telecom"
  | "/solutions/subsidy"
  | "/solutions/platform"
  | "/solutions/automation";

export type Solution = {
  /** 라우트 마지막 조각. /solutions/<slug> */
  slug: string;
  /** 라우트 경로. Link 의 to 에 그대로 넣는다 */
  path: SolutionPath;
  /** 화면 H1 — 검색어 그대로 */
  h1: string;
  /** <title> — 홈/다른 페이지와 반드시 달라야 한다 */
  metaTitle: string;
  /** <meta name="description"> */
  metaDescription: string;
  /** 히어로 위 작은 라벨 */
  eyebrow: string;
  /** 도입 2~3문장 — 그 업종에서 문의가 새는 지점 */
  intro: string;
  /** 상품 목록. 있으면 featureGroups 위에 카드로 렌더한다 */
  products?: Product[];
  /** 이 페이지의 본체 */
  featureGroups: FeatureGroup[];
  /** 랜딩에서 시스템으로 넘어가는 경로 */
  nextSteps: string[];
  /** 확장 문단 한 줄 */
  nextStepsNote: string;
  /** portfolioSites 의 이름들. 스크린샷 썸네일 + 이름만 붙이고 설명은 달지 않는다 */
  cases: string[];
  /** 토스 미니앱 사례를 사례 목록에 함께 넣는다 */
  tossMiniApp?: boolean;
  /** 페이지 맨 아래 상담 유도 문구 */
  ctaTitle: string;
  ctaBody: string;
  /** 문의 모달에 넣을 서비스명 */
  inquirySubject: string;
  /** 법정 고지 등 꼭 남겨야 하는 한 줄. 없으면 렌더하지 않는다 */
  notice?: string;
};

